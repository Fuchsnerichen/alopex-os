// Builds app/outfitting-data.js (the module list of the Outfitting tab) from EDCD FDevIDs outfitting.csv.
//   node scripts/build-outfitting-data.mjs <path/to/outfitting.csv> [source note]
// Spansh names its modules like this file, so the names double as Spansh search filters.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const [csvFile, source = 'EDCD FDevIDs outfitting.csv'] = process.argv.slice(2);
if (!csvFile) {
    console.error('Usage: node scripts/build-outfitting-data.mjs <path/to/outfitting.csv> [source note]');
    process.exit(1);
}

const [header, ...lines] = readFileSync(csvFile, 'utf8').split(/\r?\n/).filter(Boolean);
const columns = header.split(',');
const COLUMNS = ['symbol', 'category', 'name', 'class', 'rating', 'mount', 'guidance', 'ship'];
const CATEGORIES = new Set(['standard', 'internal', 'hardpoint', 'utility']);   // not: mercgear (on-foot equipment)

const modules = lines
    .map(line => Object.fromEntries(line.split(',').map((value, i) => [columns[i], value])))
    .filter(m => CATEGORIES.has(m.category) && m.name)
    .filter(m => m.entitlement !== 'removed' && m.entitlement !== '?')
    .filter(m => !/_(free|default)$/i.test(m.symbol))          // free starter modules, not for sale
    .map(m => COLUMNS.map(c => m[c] || ''));

const target = path.join(path.dirname(path.dirname(fileURLToPath(import.meta.url))), 'app', 'outfitting-data.js');
writeFileSync(target, `// Generated by scripts/build-outfitting-data.mjs from ${source}. Do not edit by hand.
// One row per module for sale: [${COLUMNS.join(', ')}]
const OUTFITTING_MODULES = [
${modules.map(m => '    ' + JSON.stringify(m)).join(',\n')}
];
`);
console.log(`${modules.length} modules -> ${target}`);
